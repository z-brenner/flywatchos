#!/usr/bin/env python3
"""Verify pinned upstream evidence and regenerate the isolated host reference data."""
if not __debug__:
    raise RuntimeError("Provenance verification requires Python without -O/PYTHONOPTIMIZE")
import argparse
import csv
import hashlib
import json
from pathlib import Path
import generate_cx_data
ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'sim/data/pisokas2020'
TABLE = ROOT / 'sim/rate_reference_connectivity.inc'
MODEL = ROOT / 'sim/rate_reference_model.json'
SOURCE_HASH = '92adf312cab38bd012fa7d68a8aca1d38ff9639c8f095a6f9df755a7b488d0b0'

def generated():
    # Validate exact upstream files and all independently extracted directed edges.
    generate_cx_data.generated()
    assert hashlib.sha256((DATA/'flyLI2.m').read_bytes()).hexdigest() == SOURCE_HASH
    provenance = json.loads((DATA/'pisokas2020_cx60_provenance.json').read_text())
    with (DATA/'pisokas2020_cx60_edges.csv').open(newline='') as stream:
        rows = list(csv.DictReader(stream))
    lines = ['/* Generated by tools/generate_rate_reference.py. Do not edit.',
             ' * Signed full-precision fitted model weights; MIT notice in source folder. */',
             'static const FlyRateEdge rate_edges[] = {']
    for row in rows:
        lines.append('    { %su, %su, %s },' % (row['source'], row['target'], row['published_model_strength']))
    lines.extend(['};', ''])
    model = {
        'schema': 1, 'id': 'pisokas-rate-core-noise-off',
        'name': 'Deterministic source-equation rate reference',
        'scope': 'host-only-source-equation-reference', 'hardware_verified': False,
        'node_count': 60, 'edge_count': 326,
        'equation': 'u_next = u + (0.0001 / 0.02) * (-u + 0.03 * sum(W[target,source] * tanh(u[source])) + 0.03 * input[target])',
        'integration': 'Synchronous explicit Euler; all incoming currents use the previous state.',
        'dt_seconds': 0.0001, 'dt_ms': 0.1, 'tau_seconds': 0.02,
        'recurrent_gain': 0.03, 'input_gain': 0.03, 'initial_u': 0,
        'units': 'Signed dimensionless u = 100 * (V - V0), with V in volts; not a firing rate. No clipping or rectification.',
        'transfer': 'Signed tanh(u), a normalized current transfer; not a spike rate.',
        'time': 'Elapsed actual Euler updates multiplied by 0.1 ms; starts at zero.',
        'inputs': {'kind': 'controlled-direct-rate-equivalent-current',
                  'range': [0, 200], 'units': 'normalized rate-equivalent current input, not Hz',
                  'cue': 'Chosen synthetic triangular profile, 90-degree half-width, centered on E-PG model-relative bins.',
                  'cue_angle_degrees': [0,45,90,135,180,225,270,315,0]*2,
                  'turn': 'Signed control selects P-EN A indices 0..7 or B indices 8..15; nonnegative injection magnitude 0..200, not calibrated angular velocity.'},
        'source_parameters': {'Cmem_farads': 2e-8, 'Rmem_ohms': 1e6, 'V0_volts': 0,
                              'inCurrent_amperes': 3e-10, 'source_noise_amperes': 3e-10},
        'limitations': ['Source Gaussian current noise is explicitly disabled.',
                       'Source centered 100 ms moving spike sum and global-maximum normalization are not reproduced.',
                       'Direct synthetic inputs are not the published stochastic stimulus pipeline.',
                       'Two disconnected padding units are omitted; exactly equivalent for 60 active units with source noise disabled.',
                       'No full-paper reproduction, biological validation, calibrated heading or watch-target validation.'],
        'limits': {'max_updates_per_call': 1000, 'max_epoch': 10000000, 'fixed_memory_bytes': 131072},
        'paper': provenance['paper'], 'repository': provenance['repository'],
        'source_commit': provenance['source_commit'],
        'source_path': 'Kakaria_deBivort_2017/KakariaPBSimulationCode.v2/flyLI2.m',
        'source_url': provenance['repository'] + '/blob/' + provenance['source_commit'] + '/Kakaria_deBivort_2017/KakariaPBSimulationCode.v2/flyLI2.m',
        'source_sha256': SOURCE_HASH,
        'source_files': provenance['files'],
        'weights': provenance['category_strengths'],
        'orientation': provenance['orientation'],
        'license': 'MIT', 'license_notice': (DATA/'LICENSE').read_text(encoding='utf-8'),
    }
    return '\n'.join(lines), json.dumps(model, indent=2, ensure_ascii=False)+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path,text in zip((TABLE,MODEL),generated()):
        if args.check:
            assert path.read_bytes()==text.encode('utf-8'), 'stale rate reference artifact: '+path.name
        else:
            path.write_text(text,encoding='utf-8',newline='\n')
    print('Rate reference: pinned source, signed weights, topology and metadata verified')
if __name__=='__main__': main()
