#!/usr/bin/env python3
"""Verify vendored provenance; generate the exact host circuit table offline.

The original MAT stores categories, NOT strengths. The CSV was derived with
sim/data/pisokas2020/export_pisokas.py (optional SciPy); no dependency or network
is required here. --check rejects stale generated C without modifying files.
"""
if not __debug__:
    raise RuntimeError("Provenance verification requires Python without -O/PYTHONOPTIMIZE")

import argparse
import csv
from decimal import Decimal, ROUND_HALF_UP
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'sim/data/pisokas2020'
OUTPUT = ROOT / 'sim/cx_connectivity.inc'
CATEGORIES = [('1.0', '6.07203896674184'), ('1.1', '47.9173822984772'),
              ('-1.0', '-35.6772759590409'), ('-1.1', '-19.3358579258735'),
              ('3.0', '99.9680554605268')]

def generated():
    provenance = json.loads((DATA / 'pisokas2020_cx60_provenance.json').read_text())
    assert provenance['source_commit'] == 'dfb95dfeaad0da2df0f7f687846d4df44079a483'
    assert provenance['source_sha256'] == 'abfdcb2918e3637e41d4ba7b7438e512f545dac6553ce89d5cfddb49de044b12'
    assert provenance['files']['pisokas2020_cx60_edges.csv']['sha256'] == 'b9066dd86199a76038eab7f288adf910a32525e2060460af06df1351d87245d0'
    for name, record in provenance['files'].items():
        contents = (DATA / name).read_bytes()
        assert len(contents) == record['bytes'], name
        assert hashlib.sha256(contents).hexdigest() == record['sha256'], name
    with (DATA / 'pisokas2020_cx60_edges.csv').open(newline='') as stream:
        rows = list(csv.DictReader(stream))
    assert len(rows) == 326
    seen = set()
    lines = ['/* Generated by tools/generate_cx_data.py. Do not edit.',
             ' * Published MODEL topology/strengths, not measured synapse counts.',
             ' * MIT attribution and unchanged source artifacts: sim/data/pisokas2020. */',
             'static const FlyCxWeight cx_weights[] = {']
    for _, strength in CATEGORIES:
        value = Decimal(strength)
        coefficient = int((value * Decimal(1024) / 100).quantize(Decimal('1'), rounding=ROUND_HALF_UP))
        lines.append(f'    {{ {abs(value)}, {coefficient} }},')
    lines.extend(['};', 'static const FlyCxEdge cx_edges[] = {'])
    for row in rows:
        source, target = int(row['source']), int(row['target'])
        kind = next(i for i, (category, _) in enumerate(CATEGORIES) if category == row['category_label'])
        assert Decimal(row['published_model_strength']) == Decimal(CATEGORIES[kind][1])
        assert 0 <= source < 60 and 0 <= target < 60
        assert (source, target) not in seen
        seen.add((source, target))
        lines.append(f'    {{ {source}u, {target}u, {kind}u }},')
    lines.extend(['};', ''])
    return '\n'.join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generated()
    if args.check:
        assert OUTPUT.read_text() == text, 'generated C graph is stale'
        print('CX provenance: pinned source hashes and all 326 generated directed edges verified')
    else:
        OUTPUT.write_text(text)

if __name__ == '__main__': main()
